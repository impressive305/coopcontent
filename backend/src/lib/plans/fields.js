// Fits any major: transferable work every organization has.
const GENERAL_FIELDS = ['إدارة المشاريع', 'تحسين العمليات', 'خدمة العملاء', 'إدخال البيانات وإعداد التقارير', 'الجودة'];

// Words of the major without the Arabic article, so "المحاسبة" is not read as "حاسب".
const words = (text) => normalize(text).split(/[\s/،,-]+/).map((w) => w.replace(/^(وال|بال|ال)/, '')).filter(Boolean);

export const suggestFields = (major = '') => {
  const tokens = words(major);
  const matched = FIELD_GROUPS.filter((g) => g.keywords.some((k) => tokens.some((t) => t.startsWith(normalize(k).trim()))));
  const fields = matched.flatMap((g) => g.fields);
  return [...new Set([...fields, ...GENERAL_FIELDS])].slice(0, 18);
};
