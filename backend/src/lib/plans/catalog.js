const normalize = (s) => s.trim().toLowerCase().replace(/\s+/g, ' ');

// Best-effort mapping of a free-text major (from the student profile) to a catalog entry.
export const matchMajor = (text = '') => {
  const value = normalize(text);
  if (!value) return null;
  return (
    MAJORS.find((m) => m.key === value || m.aliases.some((a) => normalize(a) === value)) ??
    MAJORS.find((m) => m.aliases.some((a) => a.length > 3 && value.includes(normalize(a)))) ??
    null
  );
};

export const findMajor = (key) => MAJORS.find((m) => m.key === key) ?? null;
